export function isEuropeanCountry(name: string, iso?: string) {
  const lower = name.toLowerCase();
  return EUROPE_COUNTRIES.some(
    (country) =>
      country.iso === iso ||
      country.aliases.some((alias) => alias.toLowerCase() === lower),
  );
}
